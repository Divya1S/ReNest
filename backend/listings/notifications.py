logger = logging.getLogger(__name__)

# A rescue request is worth a notification from this score (out of 10) up.
MATCH_SCORE_THRESHOLD = 7.0

_MATCH_SCORES_SCHEMA = {
    "type": "ARRAY",
    "items": {
        "type": "OBJECT",
        "properties": {"id": {"type": "INTEGER"}, "score": {"type": "NUMBER"}},
        "required": ["id", "score"],
    },
}

# Dedupe-key prefixes generated by sync_user_notifications. Only these are
# pruned when the derived set is rebuilt.
SYNC_MANAGED_PREFIXES = ("ready:", "blocked:", "task:", "reservation:", "handoff:", "repost:")

if TYPE_CHECKING:
    from accounts.models import User as UserType

User = get_user_model()


def _notification_payload(
    *,
    type: str,
    title: str,
    body: str,
    link_path: str,
    priority: str,
    dedupe_key: str,
) -> dict[str, Any]:
    return {
        "type": type,
        "title": title,
        "body": body,
        "link_path": link_path,
        "priority": priority,
        "dedupe_key": dedupe_key,
    }


def build_notification_specs_for_user(user: UserType) -> list[dict[str, Any]]:
    now = timezone.now()
    specs: list[dict[str, Any]] = []

    scan_sessions = (
        RoomScanSession.objects.filter(owner=user, is_demo=False)
        .prefetch_related("items__linked_listing", "generated_listings", "tasks")
        .order_by("-updated_at")
    )
    for session in scan_sessions:
        summary = compute_scan_summary(session)
        if summary["ready_to_publish_count"] > 0:
            specs.append(
                _notification_payload(
                    type=Notification.Type.READY_TO_PUBLISH,
                    title=f"{summary['ready_to_publish_count']} rescue draft(s) ready to publish",
                    body=(
                        f"{session.name} has publish-ready items waiting in the queue."
                    ),
                    link_path=f"/publish/{session.id}",
                    priority=Notification.Priority.NORMAL,
                    dedupe_key=f"ready:{user.id}:{session.id}:{summary['ready_to_publish_count']}",
                )
            )

        if (
            summary["missing_info_count"] > 0
            and session.move_out_deadline
            and session.move_out_deadline <= now + timedelta(hours=48)
        ):
            specs.append(
                _notification_payload(
                    type=Notification.Type.BLOCKED_SCAN,
                    title=f"{summary['missing_info_count']} draft(s) still missing info",
                    body=(
                        f"{session.name} is close to move-out. Finish the missing details before the deadline closes."
                    ),
                    link_path=f"/publish/{session.id}",
                    priority=Notification.Priority.HIGH,
                    dedupe_key=f"blocked:{user.id}:{session.id}:{summary['missing_info_count']}",
                )
            )

    tasks = (
        MoveOutTask.objects.select_related("scan_session")
        .filter(scan_session__owner=user, scan_session__is_demo=False)
        .exclude(status=MoveOutTask.Status.DONE)
    )
    for task in tasks:
        if not task.due_at or task.due_at > now + timedelta(hours=24):
            continue
        is_overdue = task.due_at < now
        specs.append(
            _notification_payload(
                type=Notification.Type.MOVE_OUT_TASK,
                title=task.title,
                body=(
                    f"{task.scan_session.name} has a task that is already overdue."
                    if is_overdue
                    else f"{task.scan_session.name} has a task due within the next 24 hours."
                ),
                link_path=f"/plan/{task.scan_session_id}",
                priority=Notification.Priority.HIGH if is_overdue else Notification.Priority.NORMAL,
                dedupe_key=f"task:{user.id}:{task.id}:{'overdue' if is_overdue else 'due-today'}",
            )
        )

    reservations = (
        Reservation.objects.select_related("listing", "listing__owner", "claimant")
        .filter(Q(claimant=user) | Q(listing__owner=user), listing__is_demo=False)
        .order_by("-updated_at")
    )
    for reservation in reservations:
        relationship = "owner" if reservation.listing.owner_id == user.id else "claimant"
        counterpart = (
            reservation.claimant.display_name
            if relationship == "owner"
            else reservation.listing.owner.display_name
        )
        action = reservation.status.replace("_", " ")
        specs.append(
            _notification_payload(
                type=Notification.Type.RESERVATION,
                title=f"{reservation.listing.title} was {action}",
                body=f"{counterpart} is connected to this handoff. Review the next step and pickup window.",
                link_path=f"/handoffs/{reservation.id}",
                priority=Notification.Priority.NORMAL,
                dedupe_key=f"reservation:{user.id}:{reservation.id}:{relationship}:{reservation.status}",
            )
        )

        if (
            reservation.status in {Reservation.Status.REQUESTED, Reservation.Status.CONFIRMED}
            and reservation.listing.available_until <= now + timedelta(hours=12)
        ):
            specs.append(
                _notification_payload(
                    type=Notification.Type.HANDOFF_URGENT,
                    title=f"Urgent handoff for {reservation.listing.title}",
                    body="This pickup window is close to the move-out deadline. Keep the handoff moving.",
                    link_path=f"/handoffs/{reservation.id}",
                    priority=Notification.Priority.HIGH,
                    dedupe_key=f"handoff:{user.id}:{reservation.id}:{relationship}:{reservation.status}",
                )
            )

    expired_with_token = (
        Listing.objects.filter(
            owner=user,
            status=Listing.Status.EXPIRED,
            is_demo=False,
            repost_token__isnull=False,
            repost_token_expires_at__gt=now,
        )
        .only("id", "title", "repost_token")
    )
    for listing in expired_with_token:
        specs.append(
            _notification_payload(
                type=Notification.Type.SYSTEM,
                title=f'"{listing.title}" expired. Repost it?',
                body="Your listing expired. One click extends it for another 7 days.",
                link_path=f"/my-listings?repost={listing.id}&token={listing.repost_token}",
                priority=Notification.Priority.LOW,
                dedupe_key=f"repost:{user.id}:{listing.id}:{listing.repost_token}",
            )
        )

    return specs


def sync_user_notifications(user: UserType) -> dict[str, int]:
    desired_specs = build_notification_specs_for_user(user)
    desired_keys = {spec["dedupe_key"] for spec in desired_specs}
    existing = {
        notification.dedupe_key: notification
        for notification in Notification.objects.filter(user=user)
    }
    to_create: list[Notification] = []
    to_update: list[Notification] = []

    for spec in desired_specs:
        notification = existing.get(spec["dedupe_key"])
        if notification is None:
            to_create.append(Notification(user=user, **spec))
            continue

        changed = False
        for field in ("type", "title", "body", "link_path", "priority"):
            value = spec[field]
            if getattr(notification, field) != value:
                setattr(notification, field, value)
                changed = True

        if changed and notification.is_read:
            notification.is_read = False
            notification.read_at = None
        if changed:
            to_update.append(notification)

    if to_create:
        Notification.objects.bulk_create(to_create)
    if to_update:
        Notification.objects.bulk_update(
            to_update,
            ["type", "title", "body", "link_path", "priority", "is_read", "read_at"],
        )

    # Only prune the derived rows this function owns. The prefixes below are
    # exactly the ones built above; everything else (chat:, dispute:, slots:,
    # pin_complete:, ai_match:, impact:, milestone:, email_handoff_reminder:)
    # is created by other flows and must survive. Deleting those used to make
    # event notifications vanish the moment the user opened their inbox.
    managed = Q()
    for prefix in SYNC_MANAGED_PREFIXES:
        managed |= Q(dedupe_key__startswith=prefix)
    Notification.objects.filter(managed, user=user).exclude(dedupe_key__in=desired_keys).delete()
    return {
        "created": len(to_create),
        "updated": len(to_update),
        "active": len(desired_specs),
    }


def same_campus_q(relation: str, user: Any) -> Q:
    """Rows whose `relation` user belongs to the same campus as `user`.

    Matching exists to arrange a hand-to-hand pickup, so a pairing across
    campuses is noise at best. Users who have not joined a campus are grouped
    by the free-text campus name they registered with (blank matches blank),
    the same fallback the rescue-request list uses.
    """
    if getattr(user, "campus_id", None):
        return Q(**{f"{relation}__campus_id": user.campus_id})
    return Q(
        **{
            f"{relation}__campus__isnull": True,
            f"{relation}__campus_name": getattr(user, "campus_name", "") or "",
        }
    )


def blocked_user_ids(user_id: int) -> set[int]:
    """Everyone `user_id` has blocked or been blocked by."""
    pairs = BlockedUser.objects.filter(Q(blocker_id=user_id) | Q(blocked_id=user_id)).values_list(
        "blocker_id", "blocked_id"
    )
    return {other for pair in pairs for other in pair if other != user_id}


def parse_match_scores(raw: Any, allowed_ids: Collection[int]) -> dict[int, float]:
    """Validated {request id: score} from the matcher's JSON answer.

    Model output is input like any other. An item is kept only when it is an
    object whose id is one of the candidates we actually sent and whose score
    is a number between 0 and 10; everything else is dropped. A string score
    used to reach `score < 7` and raise TypeError, which failed the whole
    post-create task and made its retry repeat every model call.
    """
    if not isinstance(raw, list):
        return {}
    scores: dict[int, float] = {}
    for item in raw:
        if not isinstance(item, dict):
            continue
        request_id = coerce_int(item.get("id"))
        score = coerce_number(item.get("score"))
        if request_id is None or score is None:
            continue
        if request_id not in allowed_ids or not 0.0 <= score <= 10.0:
            continue
        # A repeated id keeps its lowest score, so a duplicate cannot be used
        # to push a weak match over the threshold.
        scores[request_id] = min(score, scores.get(request_id, score))
    return scores


def notify_matching_rescue_requests(listing: Listing) -> int:
    """
    Called after a new listing is created. Asks the model to score how well the
    listing answers each open rescue request in the same category on the
    owner's campus, and creates an AI_MATCH notification for seekers whose
    request scores MATCH_SCORE_THRESHOLD or more.
    Returns the number of notifications created.
    """
    if (
        listing.is_demo
        or listing.status != Listing.Status.AVAILABLE
        or listing.moderation_status == Listing.ModerationStatus.FLAGGED
    ):
        # Seekers cannot open a listing that browse hides from them.
        return 0

    owner = listing.owner
    now = timezone.now()
    candidates = list(
        RescueRequest.objects.select_related("seeker")
        .filter(
            same_campus_q("seeker", owner),
            category=listing.category,
            status=RescueRequest.Status.OPEN,
            needed_by__gt=now,
            seeker__is_active=True,
        )
        .exclude(seeker=owner)
        .exclude(seeker_id__in=blocked_user_ids(owner.pk))
        [:20]
    )
    if not candidates:
        return 0

    if not ai_available():
        return 0

    requests_text = "\n".join(
        f"- id {req.id}: title {quote_untrusted(req.title, limit=140)}; "
        f"notes {quote_untrusted(req.description, limit=120)}"
        for req in candidates
    )

    prompt = (
        "You are a matching engine for a college campus item marketplace.\n"
        "Score how well a newly posted listing matches each rescue request on a scale of 0 to 10.\n"
        "10 = near-perfect match (same item, right condition/price), 7+ = worth notifying the seeker, "
        "below 7 = skip.\n"
        f"{UNTRUSTED_TEXT_RULE}\n\n"
        "New listing:\n"
        f"Title: {quote_untrusted(listing.title, limit=140)}\n"
        f"Description: {quote_untrusted(listing.description, limit=300)}\n\n"
        f"Open rescue requests:\n{requests_text}\n\n"
        'Respond ONLY with a JSON array: [{"id": <int>, "score": <0-10>}, ...]. No explanation.'
    )

    try:
        raw_scores = generate_json(prompt, max_tokens=300, response_schema=_MATCH_SCORES_SCHEMA)
    except Exception:
        logger.warning(
            "Rescue-request matching skipped for listing %s: the provider call failed",
            listing.pk,
            exc_info=True,
        )
        return 0

    scores = parse_match_scores(raw_scores, {req.id for req in candidates})

    created_count = 0
    category_label = listing.category.replace("_", " ").capitalize()
    for req in candidates:
        if scores.get(req.id, 0.0) < MATCH_SCORE_THRESHOLD:
            continue
        _, created = Notification.objects.get_or_create(
            user=req.seeker,
            dedupe_key=f"ai_match:{req.id}:{listing.id}",
            defaults={
                "type": Notification.Type.AI_MATCH,
                "title": f'A {category_label} listing matches your request',
                "body": (
                    f'"{listing.title}" was just posted and looks like a strong match for '
                    f'your "{req.title}" request. Check it out before move-out.'
                ),
                "link_path": f"/listings/{listing.id}",
                "priority": Notification.Priority.NORMAL,
            },
        )
        if created:
            created_count += 1

    return created_count


def sync_notifications_for_all_users() -> dict[str, int]:
    total_created = 0
    total_updated = 0
    total_active = 0
    for user in User.objects.filter(is_active=True):
        counts = sync_user_notifications(user)
        total_created += counts["created"]
        total_updated += counts["updated"]
        total_active += counts["active"]
    return {
        "created": total_created,
        "updated": total_updated,
        "active": total_active,
    }
